-- Run this script in the Supabase SQL Editor to set up the leaderboard table.
-- It is safe to rerun against an existing database.

create table if not exists public.leaderboard (
  id bigint generated by default as identity primary key,
  player_name text not null,
  score bigint not null,
  created_at timestamptz not null default timezone('utc'::text, now())
);

alter table public.leaderboard
  add column if not exists is_multiplayer boolean;

alter table public.leaderboard
  alter column is_multiplayer set default false;

alter table public.leaderboard enable row level security;

grant select, insert on public.leaderboard to anon;
grant select, insert on public.leaderboard to authenticated;

do $$
declare
  leaderboard_id_seq text;
begin
  leaderboard_id_seq := pg_get_serial_sequence('public.leaderboard', 'id');

  if leaderboard_id_seq is not null then
    execute format('grant usage, select on sequence %s to anon', leaderboard_id_seq);
    execute format('grant usage, select on sequence %s to authenticated', leaderboard_id_seq);
  end if;
end $$;

create index if not exists idx_leaderboard_score_desc
  on public.leaderboard (score desc, created_at asc);

-- Lightweight room ledger used for two-player lobby lookup and cleanup.
-- Game traffic itself stays on Trystero WebRTC to stay inside free-tier limits.
create table if not exists public.rooms (
  room_code text primary key,
  host_id text not null,
  guest_id text,
  host_character text not null default 'male',
  guest_character text not null default 'female',
  status text not null default 'waiting',
  last_seen_at timestamptz not null default timezone('utc'::text, now()),
  created_at timestamptz not null default timezone('utc'::text, now())
);

alter table public.rooms enable row level security;

grant select, insert, update on public.rooms to anon, authenticated;

create index if not exists idx_rooms_last_seen_at
  on public.rooms (last_seen_at desc);

do $$
begin
  if not exists (
    select 1
    from pg_policies
    where schemaname = 'public'
      and tablename = 'rooms'
      and policyname = 'Enable read room access for all users'
  ) then
    create policy "Enable read room access for all users"
      on public.rooms
      for select
      to anon, authenticated
      using (true);
  else
    alter policy "Enable read room access for all users"
      on public.rooms
      to anon, authenticated
      using (true);
  end if;
end $$;

